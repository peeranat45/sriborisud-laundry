/**
 * แปลงบาทที่คนพิมพ์ → สตางค์
 *
 * รับได้หลายรูปแบบที่คนพิมพ์จริง
 *   "250"      → 25000
 *   "250.5"    → 25050
 *   "250.50"   → 25050
 *   "1,250"    → 125000     (คนพิมพ์ comma มาด้วย)
 *   " 250 "    → 25000
 *
 * คืน null เมื่อใช้ไม่ได้ · ให้ชั้นบนตัดสินใจว่าจะแสดง error อะไร
 *   ""  "abc"  "-5"  "250.555"  "1e5"
 *
 * ❗ ไม่แปลงผ่าน Math.round(parseFloat(v) * 100)
 *    เพราะ parseFloat("1.005") * 100 ได้ 100.49999999999999 ไม่ใช่ 100.5
 *    ค่าที่อยู่ตรงเส้นปัดจึงตกไปผิดข้างเป็นบางค่า และเดาไม่ได้ว่าค่าไหน
 *    จึงตัดสตริงเป็นสองส่วนแล้วประกอบเป็นจำนวนเต็มตรงๆ · ไม่มี Float คั่นกลาง
 */
export function bahtToSatang(input: string): number | null {
  const s = input.trim().replace(/,/g, "");
  if (s === "") return null;

  // เลขจำนวนเต็ม หรือ เลขที่มีทศนิยม 1-2 ตำแหน่ง · ห้ามติดลบ ห้าม exponent
  const m = /^(\d+)(?:\.(\d{1,2}))?$/.exec(s);
  if (!m) return null;

  const baht = Number(m[1]);
  // "250.5" → "5" → ต้องเติม 0 ข้างหลังให้เป็น "50" = 50 สตางค์
  const satang = Number((m[2] ?? "0").padEnd(2, "0"));

  // กันเลขใหญ่เกินกว่าที่ Int ของ Postgres รับได้ (2,147,483,647 สตางค์)
  const total = baht * 100 + satang;
  if (!Number.isSafeInteger(total) || total > 2_147_483_647) return null;

  return total;
}

/**
 * สตางค์ → ข้อความบาทสำหรับแสดงบนจอ
 *   25050  → "250.50"
 *   125000 → "1,250.00"
 *
 * ทศนิยมสองตำแหน่งเสมอ แม้จะเป็น .00
 * เพราะเลขที่ความยาวไม่เท่ากันทำให้ตาไล่ยอดในตารางยาก
 */
export function formatBaht(satang: number): string {
  const sign = satang < 0 ? "-" : "";
  const abs = Math.abs(satang);
  const baht = Math.floor(abs / 100);
  const rest = abs % 100;
  return `${sign}${baht.toLocaleString("en-US")}.${String(rest).padStart(2, "0")}`;
}
